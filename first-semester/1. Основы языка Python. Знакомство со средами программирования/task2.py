# Напишите программу, которая рассчитывает доход от инвестиций с
# заданным доходом за год и количеством лет.


print("Введите исходные данные:")
value = int(input("Сумма инвестиций (руб.) -> "))
period = int(input("Количество лет -> "))
percent = int(input("Годовой доход (в процентах) -> "))
total = round(value*(1+percent/100)**period ,2)
print("Итоговая сумма: " + str(total) + " руб.")

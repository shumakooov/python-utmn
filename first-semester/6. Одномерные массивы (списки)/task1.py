# Вычислить сумму четных элементов массива кратных 7 и 9.

my_list = [1, 9, 12, 56, 23, 100, 21, 2, 7, 63, 126]

amount = 0

for i in my_list: 
    if i % 2 == 0 and i % 7 == 0 and i % 9 == 0:
        amount+= i

print(f"Сумма четных элементов кратных 7 и 9 = {amount}")
print(f"Весь массив: {my_list}")

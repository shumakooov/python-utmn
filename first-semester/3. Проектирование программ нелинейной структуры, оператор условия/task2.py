# Дана точка на плоскости с координатами (х, у). Составить программу,
# которая определяет принадлежит ли точка заштрихованной области включая ее
# границы.
# img/1.3.2.png

import math
x = float(input("Введите значение X: "))
y = float(input("Введите значение Y: "))
if x >= 0 and 0 <= y <= math.sin(x) and y <= 0.5:
    print("Точка принадлежит заштрихованной области.")
else:
    print("Точка не принадлежит заштрихованной области.")

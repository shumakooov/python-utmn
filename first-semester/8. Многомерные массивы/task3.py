# Дан двумерный массив размерностью N*M. Сформировать одномерный массив, каждый элемент которого равен количеству элементов соответствующей строки, больших числа А, число А вводиться с клавиатуры.

array = [
    [45, -32, 77, -10, 88],
    [-55, 20, -91, 30, 6],
    [90, -15, 40, 75, -80],
    [25, 60, -47, 10, 95],
]

A = int(input("Введите число A: "))

result = []
for row in array:
    count = 0
    for element in row:
        if element > A:
            count += 1
    result.append(count)

print("\nИсходный массив:")
for row in array:
    print(row)
print()

print(f"Полученный массив (количество элементов > A в каждой строке): {result}")

import json

# Глобальный словарь для хранения глоссария
glossary = {
    "ежики": "семейство млекопитающих отряда насекомоядных",
    "кролики": "это не только ценный мех",
    "индексация": "обращение к отдельному символу строки по его порядковому номеру (индексу)",
    "пример_1": "#Подсчет количества символов в строке\ntext = input(\"Введите строку: \")\nprint(f\"Количество символов: {len(text)}\")",
    "пример_2": "#Реверс строки\nstring = \"hello world\"\n reversed_string = string[::-1]\nprint(f\"Исходная строка: {string}\")\nprint(f\"Перевернутая строка: {reversed_string}\")",
    "пример_3": "#Подсчет количества слов в строке\ntext = \"Python это мощный язык программирования\"\nwords = text.split()\nprint(f\"Количество слов: {len(words)}\")",
    "пример_4": "#Проверка палиндрома\nword = \"топот\"\nis_palindrome = word == word[::-1]\nprint(f\"Слово '{word}' {'является' if is_palindrome else 'не является'} палиндромом\")",
    "пример_5": "#Замена символов в строке\ntext = \"Hello World!\"\nnew_text = text.replace(\"o\", \"0\")\nprint(f\"Исходная строка: {text}\")\nprint(f\"Измененная строка: {new_text}\")"
    }

def display_glossary():
    print("\n=== ГЛОССАРИЙ ===")
    
    if not glossary:
        print("Глоссарий пуст.")
        return
    
    for (term, definition) in glossary.items():
        print(f"{term}: {definition}")
    
    print(f"\nВсего терминов: {len(glossary)}")

def save_glossary():
    if not glossary:
        print("Глоссарий пуст. Нечего сохранять.")
        return
    
    filename = input("Введите имя файла для сохранения (по умолчанию: glossary.json): ")
    if not filename:
        filename = "glossary.json"
    
    try:
        with open(filename, 'w', encoding='utf-8') as file:
            json.dump(glossary, file, ensure_ascii=False, indent=2)
        print(f"Глоссарий успешно сохранен в файл '{filename}'!")
    except Exception as e:
        print(f"Ошибка при сохранении файла: {e}")

def delete_term():
    term = input("Введите термин для удаления: ").strip()
    
    if term in glossary:
        del glossary[term]
        print(f"Термин '{term}' успешно удален из глоссария!")
    else:
        print(f"Термин '{term}' не найден в глоссарии.")

def search_term():
    term = input("Введите термин для поиска: ").strip()
    
    if term in glossary:
        print(f"\n{term}: {glossary[term]}")
    else:
        print(f"Термин '{term}' не найден в глоссарии.")

def add_term():
    print("\n=== ДОБАВЛЕНИЕ ТЕРМИНА ===")
    
    term = input("Введите термин: ").strip()
    if not term:
        print("Термин не может быть пустым!")
        return
    
    if term in glossary:
        print(f"Термин '{term}' уже существует в глоссарии.")
        overwrite = input("Перезаписать? (да/нет): ").strip().lower()
        if overwrite != 'да':
            return
    
    definition = input("Введите определение термина: ").strip()
    if not definition:
        print("Определение не может быть пустым!")
        return
    
    glossary[term] = definition
    print(f"Термин '{term}' успешно добавлен в глоссарий!")

def main():
    while True:
        print("\n" + "="*50)
        print("           ГЛОССАРИЙ - ГЛАВНОЕ МЕНЮ")
        print("="*50)
        print("1. Показать глоссарий")
        print("2. Сохранить глоссарий в файл")
        print("3. Добавить термин")
        print("4. Удалить термин")
        print("5. Поиск термина")
        print("6. Выход")
        print("="*50)
        
        choice = input("Выберите действие (1-6): ").strip()
        
        if choice == '1':
            display_glossary()
        elif choice == '2':
            save_glossary()
        elif choice == '3':
            add_term()
        elif choice == '4':
            delete_term()
        elif choice == '5':
            search_term()
        elif choice == '6':
            print("До свидания!")
            break
        else:
            print("Неверный выбор. Пожалуйста, выберите действие от 1 до 6.")

main()

# Вычислить сумму ряда с точностью ε, общий член которого указан в варианте.
# Точность считается достигнутой, если следующий член последовательности меньше
# заданного ε
# img/1.4.3.png

import math
e = 0.0001
n = 1
count = 0
while True:
    term = math.factorial(n) / (n ** n)
    if term < e:
        break
    count += term
    n += 1
print("Сумма ряда с точностью e =", count)
